use std::collections::BTreeMap;
use std::fs;
use std::io::ErrorKind;
use std::path::Path;

use anyhow::{Context, Result, bail};
use serde::{Deserialize, Serialize};

use crate::manifest::{CommandOrigin, GitOrigin};

pub const VERSION: u32 = 3;
/// Locks with plugins are version 4, so an older skl refuses them rather than
/// silently dropping the plugins when it rewrites the lock.
pub const PLUGINS: u32 = 4;
const HEADER: &str = "# Generated by skl. Run `skl update` to move skills to newer commits.\n\n";

/// Exact commits for every git skill, so each machine installs the same content.
#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
#[serde(try_from = "Stored", into = "Stored")]
pub struct Lock {
    pub version: u32,
    /// App snapshots: single command imports and members of app sources.
    pub commands: BTreeMap<String, CommandSkill>,
    /// Complete membership of wildcard sources, by alias.
    pub repositories: BTreeMap<String, crate::repositories::Coverage>,
    pub skills: BTreeMap<String, LockedSkill>,
    pub plugins: BTreeMap<String, LockedPlugin>,
}

/// A plugin pinned to a commit, with the folder each agent installs.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct LockedPlugin {
    pub source: String,
    #[serde(rename = "ref", default, skip_serializing_if = "Option::is_none")]
    pub git_ref: Option<String>,
    /// The plugin's name in the repository's marketplace.
    pub plugin: String,
    pub commit: String,
    /// The plugin folder for each agent, empty for the repository root.
    pub subdirs: BTreeMap<String, String>,
}

/// The lock as written. Members of an app source share its command and app
/// version, so each records only its digest. Version 2 kept Xcode exports in their
/// own `[xcode]` table, and versions 1 and 2 kept coverage under `[repositories]`.
#[derive(Serialize, Deserialize)]
struct Stored {
    version: u32,
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    commands: BTreeMap<String, CommandSkill>,
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    sources: BTreeMap<String, Source>,
    #[serde(default, skip_serializing)]
    repositories: BTreeMap<String, crate::repositories::Coverage>,
    #[serde(default, skip_serializing)]
    xcode_all_complete: bool,
    #[serde(default)]
    skills: BTreeMap<String, LockedSkill>,
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    plugins: BTreeMap<String, LockedPlugin>,
    #[serde(default, skip_serializing)]
    xcode: BTreeMap<String, Provenance>,
}

/// A declared source in the lock: its wildcard coverage and, for an app source,
/// the command and app version its member snapshots share.
#[derive(Default, Serialize, Deserialize)]
struct Source {
    #[serde(default, skip_serializing_if = "String::is_empty")]
    source: String,
    #[serde(rename = "ref", default, skip_serializing_if = "Option::is_none")]
    git_ref: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    subdir: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    command: Option<Vec<String>>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    version_command: Option<Vec<String>>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    timeout: Option<u64>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    version: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    members: Option<BTreeMap<String, String>>,
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    snapshots: BTreeMap<String, Member>,
}

impl Source {
    fn producer(&self) -> Result<Option<CommandOrigin>, String> {
        let Some(command) = &self.command else {
            return Ok(None);
        };
        let timeout = self
            .timeout
            .ok_or("an app source command needs a timeout")?;
        Ok(Some(CommandOrigin {
            command: command.clone(),
            version_command: self.version_command.clone(),
            timeout,
        }))
    }

    fn set_producer(&mut self, producer: &CommandOrigin) {
        self.command = Some(producer.command.clone());
        self.version_command = producer.version_command.clone();
        self.timeout = Some(producer.timeout);
    }
}

/// A member's digest, or a table when its export differs from the source's.
#[derive(Serialize, Deserialize)]
#[serde(untagged)]
enum Member {
    Digest(String),
    Own {
        digest: String,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        version: Option<String>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        producer: Option<CommandOrigin>,
    },
}

impl TryFrom<Stored> for Lock {
    type Error = String;

    fn try_from(stored: Stored) -> Result<Self, String> {
        let mut lock = Self {
            version: stored.version,
            commands: stored.commands,
            repositories: stored.repositories,
            skills: stored.skills,
            plugins: stored.plugins,
        };
        for (alias, source) in stored.sources {
            let producer = source
                .producer()
                .map_err(|e| format!("source `{alias}`: {e}"))?;
            if !source.source.is_empty() || source.members.is_some() {
                let coverage = crate::repositories::Coverage {
                    producer: if source.source.is_empty() {
                        producer.clone()
                    } else {
                        None
                    },
                    source: source.source,
                    git_ref: source.git_ref,
                    subdir: source.subdir,
                    members: source.members.unwrap_or_default(),
                };
                lock.repositories.insert(alias.clone(), coverage);
            }
            for (name, member) in source.snapshots {
                let (digest, version, own) = match member {
                    Member::Digest(digest) => (digest, None, None),
                    Member::Own {
                        digest,
                        version,
                        producer,
                    } => (digest, version, producer),
                };
                let entry = CommandSkill {
                    producer: own
                        .or_else(|| producer.clone())
                        .ok_or_else(|| format!("source `{alias}` has no command for `{name}`"))?,
                    repository: Some(alias.clone()),
                    snapshot: Provenance {
                        version: version.or_else(|| source.version.clone()).ok_or_else(|| {
                            format!("source `{alias}` has no app version for `{name}`")
                        })?,
                        digest,
                    },
                };
                if lock.commands.insert(name.clone(), entry).is_some() {
                    return Err(format!("`{name}` is locked twice"));
                }
            }
        }
        let producer = crate::export::Preset::Xcode.producer(None);
        if stored.xcode_all_complete {
            lock.repositories.insert(
                crate::export::XCODE.into(),
                crate::repositories::Coverage {
                    source: String::new(),
                    git_ref: None,
                    subdir: None,
                    producer: Some(producer.clone()),
                    members: stored
                        .xcode
                        .keys()
                        .map(|n| (n.clone(), n.clone()))
                        .collect(),
                },
            );
        }
        for (name, snapshot) in stored.xcode {
            lock.commands.insert(
                name,
                CommandSkill {
                    producer: producer.clone(),
                    repository: Some(crate::export::XCODE.into()),
                    snapshot,
                },
            );
        }
        Ok(lock)
    }
}

impl From<Lock> for Stored {
    fn from(lock: Lock) -> Self {
        let mut sources: BTreeMap<String, Source> = lock
            .repositories
            .into_iter()
            .map(|(alias, coverage)| {
                let mut source = Source {
                    source: coverage.source,
                    git_ref: coverage.git_ref,
                    subdir: coverage.subdir,
                    members: Some(coverage.members),
                    ..Source::default()
                };
                if let Some(producer) = &coverage.producer {
                    source.set_producer(producer);
                }
                (alias, source)
            })
            .collect();
        let mut commands = BTreeMap::new();
        let mut members: BTreeMap<String, Vec<(String, CommandSkill)>> = BTreeMap::new();
        for (name, entry) in lock.commands {
            match entry.repository.clone() {
                Some(alias) => members.entry(alias).or_default().push((name, entry)),
                None => {
                    commands.insert(name, entry);
                }
            }
        }
        for (alias, entries) in members {
            let source = sources.entry(alias).or_default();
            // An app source's coverage names its command. Otherwise use the command
            // and version most members share, so only the exceptions repeat them.
            let producer = match source.producer() {
                Ok(Some(producer)) if source.source.is_empty() => producer,
                _ => most_common(entries.iter().map(|(_, e)| &e.producer))
                    .cloned()
                    .expect("an app source has members"),
            };
            let version = most_common(
                entries
                    .iter()
                    .filter(|(_, e)| e.producer == producer)
                    .map(|(_, e)| &e.snapshot.version),
            )
            .cloned();
            source.set_producer(&producer);
            for (name, entry) in entries {
                let own_version = (Some(&entry.snapshot.version) != version.as_ref())
                    .then_some(entry.snapshot.version);
                let own_producer = (entry.producer != producer).then_some(entry.producer);
                let member = if own_version.is_none() && own_producer.is_none() {
                    Member::Digest(entry.snapshot.digest)
                } else {
                    Member::Own {
                        digest: entry.snapshot.digest,
                        version: own_version,
                        producer: own_producer,
                    }
                };
                source.snapshots.insert(name, member);
            }
            source.version = version;
        }
        Self {
            version: lock.version,
            commands,
            sources,
            repositories: BTreeMap::new(),
            xcode_all_complete: false,
            skills: lock.skills,
            plugins: lock.plugins,
            xcode: BTreeMap::new(),
        }
    }
}

/// The value most items share, preferring the earliest on a tie.
fn most_common<'a, T: PartialEq>(values: impl Iterator<Item = &'a T>) -> Option<&'a T> {
    let mut counts: Vec<(&T, usize)> = Vec::new();
    for value in values {
        match counts.iter_mut().find(|(seen, _)| *seen == value) {
            Some((_, count)) => *count += 1,
            None => counts.push((value, 1)),
        }
    }
    counts
        .into_iter()
        .rev()
        .max_by_key(|(_, count)| *count)
        .map(|(value, _)| value)
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct LockedSkill {
    pub source: String,
    #[serde(rename = "ref", default, skip_serializing_if = "Option::is_none")]
    pub git_ref: Option<String>,
    pub commit: String,
    /// Directory inside the repo holding SKILL.md, empty for the repo root.
    #[serde(default, skip_serializing_if = "String::is_empty")]
    pub subdir: String,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Provenance {
    pub version: String,
    pub digest: String,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct CommandSkill {
    pub producer: CommandOrigin,
    /// The app source whose export provided this skill, if any.
    #[serde(
        rename = "source",
        alias = "repository",
        default,
        skip_serializing_if = "Option::is_none"
    )]
    pub repository: Option<String>,
    pub snapshot: Provenance,
}

impl LockedSkill {
    /// Whether this entry still describes what the manifest asks for. Editing the
    /// source, ref or subdir in the manifest makes skl resolve the skill again.
    pub fn matches(&self, origin: &GitOrigin) -> bool {
        self.source == origin.source
            && self.git_ref == origin.git_ref
            && match &origin.subdir {
                Some(dir) => *dir == self.subdir,
                // A name found outside a source's new `subdir` is looked up again.
                None => crate::git::within(&self.subdir, origin.scope.as_deref()),
            }
    }
}

impl Lock {
    pub fn load(path: &Path) -> Result<Self> {
        let text = match fs::read_to_string(path) {
            Ok(text) => text,
            Err(err) if err.kind() == ErrorKind::NotFound => {
                return Ok(Self {
                    version: VERSION,
                    ..Self::default()
                });
            }
            Err(err) => return Err(err).with_context(|| format!("reading {}", path.display())),
        };
        let lock: Self = toml::from_str(&text)
            .with_context(|| format!("invalid lockfile {}", path.display()))?;
        if !(1..=PLUGINS).contains(&lock.version) {
            bail!(
                "{} has version {}, this skl reads up to version {PLUGINS}",
                path.display(),
                lock.version
            );
        }
        for (name, entry) in &lock.plugins {
            crate::manifest::validate_name(name)?;
            for (agent, dir) in &entry.subdirs {
                if crate::plugins::Harness::named(agent).is_none()
                    || (!dir.is_empty() && crate::manifest::directory(dir)?.as_ref() != Some(dir))
                {
                    bail!("invalid folder for plugin `{name}` in {}", path.display());
                }
            }
        }
        for (alias, coverage) in &lock.repositories {
            crate::manifest::validate_name(alias)?;
            if let Some(scope) = &coverage.subdir
                && crate::manifest::directory(scope)?.as_ref() != Some(scope)
            {
                bail!(
                    "invalid directory for source `{alias}` in {}",
                    path.display()
                );
            }
            for (name, subdir) in &coverage.members {
                crate::manifest::validate_name(name)?;
                if subdir.starts_with('/')
                    || (!subdir.is_empty()
                        && subdir
                            .split('/')
                            .any(|part| matches!(part, ".." | "." | "")))
                {
                    bail!(
                        "invalid repository directory for `{name}` in {}",
                        path.display()
                    );
                }
            }
        }
        for (name, entry) in &lock.commands {
            crate::manifest::validate_name(name)?;
            let digest = &entry.snapshot.digest;
            if digest.len() != 64 || !digest.bytes().all(|b| b.is_ascii_hexdigit()) {
                bail!(
                    "invalid app snapshot digest for `{name}` in {}",
                    path.display()
                );
            }
        }
        Ok(lock)
    }

    pub fn save(&self, path: &Path) -> Result<()> {
        let mut current = self.clone();
        current.version = if current.plugins.is_empty() {
            VERSION
        } else {
            PLUGINS
        };
        let body = toml::to_string(&current)?;
        crate::write_atomic(path, format!("{HEADER}{body}").as_bytes())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::repositories::Coverage;

    fn producer(command: &str) -> CommandOrigin {
        CommandOrigin {
            command: vec![command.into(), "{output}".into()],
            version_command: None,
            timeout: 30,
        }
    }

    fn member(alias: &str, command: &str, version: &str, digest: char) -> CommandSkill {
        CommandSkill {
            producer: producer(command),
            repository: Some(alias.into()),
            snapshot: Provenance {
                version: version.into(),
                digest: digest.to_string().repeat(64),
            },
        }
    }

    #[test]
    fn app_members_share_their_source_and_round_trip() {
        let mut lock = Lock {
            version: VERSION,
            ..Lock::default()
        };
        lock.repositories.insert(
            "team".into(),
            Coverage {
                source: "acme/skills".into(),
                git_ref: Some("main".into()),
                subdir: Some("skills".into()),
                producer: None,
                members: [("review".into(), "skills/review".into())].into(),
            },
        );
        lock.repositories.insert(
            "tools".into(),
            Coverage {
                source: String::new(),
                git_ref: None,
                subdir: None,
                producer: Some(producer("export")),
                members: [
                    ("a".into(), "a".into()),
                    ("hidden".into(), "x/hidden".into()),
                ]
                .into(),
            },
        );
        lock.commands
            .insert("a".into(), member("tools", "export", "2", 'a'));
        lock.commands
            .insert("b".into(), member("tools", "export", "1", 'b'));
        lock.commands
            .insert("c".into(), member("tools", "old", "1", 'c'));
        lock.commands
            .insert("d".into(), member("tools", "export", "2", 'd'));
        lock.commands
            .insert("e".into(), member("listed", "list", "7", 'e'));
        let mut single = member("", "single", "1", 'f');
        single.repository = None;
        lock.commands.insert("f".into(), single);

        let text = toml::to_string(&lock).unwrap();
        assert!(text.contains(
            "[sources.team]\nsource = \"acme/skills\"\nref = \"main\"\nsubdir = \"skills\""
        ));
        assert!(
            text.contains(&format!("a = \"{}\"", "a".repeat(64))),
            "{text}"
        );
        assert!(
            text.contains(&format!("e = \"{}\"", "e".repeat(64))),
            "{text}"
        );
        assert!(!text.contains("[sources.listed.members]"), "{text}");
        let b = format!(
            "[sources.tools.snapshots.b]\ndigest = \"{}\"\nversion = \"1\"\n",
            "b".repeat(64)
        );
        assert!(text.contains(&b), "{text}");
        assert!(
            text.contains("[sources.tools.snapshots.c.producer]"),
            "{text}"
        );
        assert!(text.contains("[commands.f.producer]"), "{text}");
        assert!(!text.contains("[repositories"), "{text}");
        assert_eq!(text.matches("\"export\"").count(), 1, "{text}");
        assert_eq!(toml::from_str::<Lock>(&text).unwrap(), lock);
    }

    #[test]
    fn earlier_locks_keep_coverage_under_repositories() {
        let lock: Lock = toml::from_str(
            "version = 2\n[repositories.team]\nsource = \"acme/skills\"\n[repositories.team.members]\nreview = \"skills/review\"\n",
        )
        .unwrap();
        assert_eq!(lock.repositories["team"].members["review"], "skills/review");
        assert!(
            toml::to_string(&lock)
                .unwrap()
                .contains("[sources.team.members]")
        );
    }

    #[test]
    fn members_need_a_command_and_version() {
        let digest = "a".repeat(64);
        for text in [
            format!(
                "version = 3\n[sources.tools]\nversion = \"1\"\n[sources.tools.snapshots]\na = \"{digest}\"\n"
            ),
            format!(
                "version = 3\n[sources.tools]\ncommand = [\"x\"]\ntimeout = 30\n[sources.tools.snapshots]\na = \"{digest}\"\n"
            ),
            "version = 3\n[sources.tools]\ncommand = [\"x\"]\n[sources.tools.members]\n".into(),
        ] {
            assert!(toml::from_str::<Lock>(&text).is_err(), "{text}");
        }
    }
}
